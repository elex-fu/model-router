for (const vector of vectors) {
  test(`sigv4 vector: ${vector.name} — canonical request`, () => {
    assert.equal(sigv4CanonicalRequest(vector.request), vector.expectedCanonical);
  });

  test(`sigv4 vector: ${vector.name} — string to sign`, () => {
    assert.equal(sigv4StringToSign(vector.request, vector.expectedCanonical), vector.expectedStringToSign);
  });

  test(`sigv4 vector: ${vector.name} — signature`, () => {
    const key = sigv4SigningKey(
      vector.credential.secretAccessKey,
      vector.request.dateStamp,
      vector.request.region,
      vector.request.service,
    );
    assert.equal(sigv4Signature(key, vector.expectedStringToSign), vector.expectedSignature);
  });

  test(`sigv4 vector: ${vector.name} — full Authorization header`, () => {
    const signed = signSigV4(vector.credential, vector.request);
    assert.equal(signed.authorization, vector.expectedAuthorization);
    assert.equal(
      signed.payloadHash,
      vector.request.payload.length === 0
        ? 'e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855'
        : sigv4PayloadHash(vector.request.payload),
    );
  });
}

test('sigv4 rejects an x-amz-content-sha256 header that disagrees with the payload', () => {
  const base = vectors[3].request;
  assert.throws(
    () =>
      signSigV4(vectors[3].credential, {
        ...base,
        headers: { ...base.headers, 'x-amz-content-sha256': '0'.repeat(64) },
      }),
    /does not match the payload/,
  );
});

test('sigv4UriEncode percent-encodes reserved characters with uppercase hex and keeps unreserved ones', () => {
  assert.equal(sigv4UriEncode('aA9-._~'), 'aA9-._~');
  assert.equal(sigv4UriEncode('a b+c/d'), 'a%20b%2Bc%2Fd');
  assert.equal(sigv4UriEncode('a/b', false), 'a/b');
  assert.equal(sigv4UriEncode('é'), '%C3%A9');
});

test('sigv4AmzDate renders the ISO 8601 basic form', () => {
  assert.equal(sigv4AmzDate(Date.parse('2026-01-17T09:15:03.250Z')), '20260117T091503Z');
});

test('signBedrockRequest assembles exactly the AWS header set and the Authorization header', () => {
  const payload = Buffer.from(
    '{"anthropic_version":"bedrock-2023-05-31","max_tokens":16,"messages":[{"role":"user","content":"2+2=?"}]}',
    'utf8',
  );
  const { headers, payloadHash } = signBedrockRequest({
    credential: {
      accessKeyId: VECTOR_ACCESS_KEY,
      secretAccessKey: VECTOR_SECRET,
      sessionToken: 'IQoJb3JpZ2luX2VxEXAMPLE==',
    },
    method: 'POST',
    host: 'bedrock-runtime.us-west-2.amazonaws.com',
    path: '/model/us.anthropic.claude-sonnet-4-5-v1%3A0/invoke',
    payload,
    region: 'us-west-2',
    nowMs: Date.parse('2026-01-17T09:15:03Z'),
  });
  // The litellm lesson contract: only Content-Type/Accept plus the AWS
  // headers — no other client header may ever enter the signature.
  assert.deepEqual(Object.keys(headers).sort(), [
    'accept',
    'authorization',
    'content-type',
    'host',
    'x-amz-content-sha256',
    'x-amz-date',
    'x-amz-security-token',
  ]);
  assert.equal(headers['x-amz-date'], '20260117T091503Z');
  assert.equal(headers['x-amz-content-sha256'], payloadHash);
  assert.equal(
    headers.authorization,
    'AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260117/us-west-2/bedrock/aws4_request, SignedHeaders=accept;content-type;host;x-amz-content-sha256;x-amz-date;x-amz-security-token, Signature=ccdbe67441c62399f43901e8134e55e24f6d6b85dfafd79e9841233cb139d67a',
  );
});

test('signBedrockRequest omits x-amz-security-token when the credential carries no session token', () => {
  const payload = Buffer.from('{"anthropic_version":"bedrock-2023-05-31"}', 'utf8');
  const { headers } = signBedrockRequest({
    credential: { accessKeyId: VECTOR_ACCESS_KEY, secretAccessKey: VECTOR_SECRET },
    method: 'POST',
    host: 'bedrock-runtime.eu-central-1.amazonaws.com',
    path: '/model/eu.anthropic.claude-opus-4-6-v1%3A0/invoke-with-response-stream',
    payload,
    region: 'eu-central-1',
    nowMs: Date.parse('2026-01-17T09:15:03Z'),
  });
  assert.equal('x-amz-security-token' in headers, false);
  assert.match(
    headers.authorization,
    /SignedHeaders=accept;content-type;host;x-amz-content-sha256;x-amz-date, Signature=03d3409b9b44748ca07e33e1717bf9f3a7099f7d426fa88c36a99303e6152a43/,
  );
});
